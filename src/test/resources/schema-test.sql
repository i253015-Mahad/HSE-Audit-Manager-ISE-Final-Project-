-- H2-compatible schema for integration tests (mirrors src/main/resources/schema.sql).
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- Projects (Project Management) — mirrors src/main/resources/schema.sql.
-- manager_email = the ONE Manager (FR-31); state/closed_at = lifecycle (FR-32+).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS projects (
    id            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(200) NOT NULL,
    manager_email VARCHAR(200),
    state         VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    closed_at     TIMESTAMP,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT uq_projects_name UNIQUE (name)
);

CREATE INDEX IF NOT EXISTS idx_projects_manager_email ON projects (manager_email);

-- Slice 3 tables (mirrors src/main/resources/schema.sql), added for the merged app.
CREATE TABLE IF NOT EXISTS inspector_designation (
    inspector_email VARCHAR(255) NOT NULL,
    manager_email   VARCHAR(255),
    CONSTRAINT pk_inspector_designation PRIMARY KEY (inspector_email)
);

CREATE TABLE IF NOT EXISTS safety_report (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id        BIGINT NOT NULL,
    inspector_email   VARCHAR(255) NOT NULL,
    incident_date     DATE NOT NULL,
    incident_time     TIME NOT NULL,
    location          VARCHAR(255) NOT NULL,
    incident_type     VARCHAR(255) NOT NULL,
    submission_status VARCHAR(255) NOT NULL,
    progress_status   VARCHAR(255),
    deleted           BOOLEAN NOT NULL DEFAULT FALSE,
    submitted_at      TIMESTAMP NOT NULL,
    CONSTRAINT pk_safety_report PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS safety_violation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    report_id             BIGINT NOT NULL,
    description           VARCHAR(2000) NOT NULL,
    hazard_category       VARCHAR(255) NOT NULL,
    hazard_category_other VARCHAR(255),
    severity_level        VARCHAR(255) NOT NULL,
    severity_level_other  VARCHAR(255),
    immediate_action      VARCHAR(2000),
    CONSTRAINT pk_safety_violation PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS report_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    report_id       BIGINT NOT NULL,
    version_number  INT NOT NULL,
    submitted_at    TIMESTAMP NOT NULL,
    project_id      BIGINT NOT NULL,
    inspector_email VARCHAR(255) NOT NULL,
    incident_date   DATE NOT NULL,
    incident_time   TIME NOT NULL,
    location        VARCHAR(255) NOT NULL,
    incident_type   VARCHAR(255) NOT NULL,
    violations_json TEXT NOT NULL,
    CONSTRAINT pk_report_version PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS photograph_evidence (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    violation_id       BIGINT NOT NULL,
    stored_file_name   VARCHAR(255) NOT NULL,
    original_file_name VARCHAR(255),
    content_type       VARCHAR(255) NOT NULL,
    size_bytes         BIGINT NOT NULL,
    CONSTRAINT pk_photograph_evidence PRIMARY KEY (id),
    CONSTRAINT uq_photo_file UNIQUE (stored_file_name)
);

CREATE TABLE IF NOT EXISTS submission_token (
    token      VARCHAR(255) NOT NULL,
    report_id  BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_submission_token PRIMARY KEY (token)
);
